package com.project.Employee.service;

import java.util.List;

import org.springframework.stereotype.Service;

import com.project.Employee.exception.DuplicateEmailException;
import com.project.Employee.exception.EmployeeNotFoundException;
import com.project.Employee.exception.InvalidEmployeeException;
import com.project.Employee.model.Manager;
import com.project.Employee.repo.Employeerepo;

@Service
public class Employeeservices implements Employeeservice {

    private final Employeerepo employeerepo;

    public Employeeservices(Employeerepo employeerepo) {
        this.employeerepo = employeerepo;
    }

    // POST: Create employee
    @Override
    public Manager createManagerdata(Manager m) {
        validate(m);
        String gmail = m.getGmail().trim();
        m.setGmail(gmail);
        m.setEname(m.getEname().trim());

        // CHANGED: eid is generated by MySQL. If a client sends an eid, ignore it,
        // otherwise save() would OVERWRITE that existing employee instead of creating
        // one.
        m.setEid(null);

        if (employeerepo.existsByGmailIgnoreCase(gmail)) {
            throw new DuplicateEmailException(gmail);
        }
        return employeerepo.save(m);
    }

    // GET: All employees
    @Override
    public List<Manager> getAllmanagerinfo() {
        return employeerepo.findAll();
    }

    // GET: Employee by ID
    @Override
    public Manager getManager(Integer eid) {
        // CHANGED: was .orElse(null) which returned HTTP 200 with an empty body
        return employeerepo.findById(eid)
                .orElseThrow(() -> EmployeeNotFoundException.withId(eid));
    }

    // PUT: Update employee
    @Override
    public Manager updatedata(Integer eid, Manager m) {

        Manager existing = employeerepo.findById(eid)
                .orElseThrow(() -> EmployeeNotFoundException.withId(eid));

        validate(m);
        String gmail = m.getGmail().trim();

        if (employeerepo.existsByGmailIgnoreCaseAndEidNot(gmail, eid)) {
            throw new DuplicateEmailException(gmail);
        }

        existing.setEname(m.getEname().trim());
        existing.setAge(m.getAge());
        existing.setSalary(m.getSalary());
        existing.setGmail(gmail);
        existing.setPhoneno(m.getPhoneno());

        return employeerepo.save(existing);
    }

    // DELETE: Employee by ID
    @Override
    public void deletedata(Integer eid) {

        if (!employeerepo.existsById(eid)) {
            throw EmployeeNotFoundException.withId(eid);
        }

        employeerepo.deleteById(eid);
    }

    // GET: Employee by Gmail
    @Override
    public Manager findbyEmail(String gmail) {
        // CHANGED: was returning null (HTTP 200, empty body) when nothing matched
        return employeerepo.findFirstByGmailIgnoreCase(gmail)
                .orElseThrow(() -> EmployeeNotFoundException.withEmail(gmail));
    }

    // DELETE: all employees
    @Override
    public void deleteAlldata() {
        employeerepo.deleteAll();
    }

    // Light server-side validation (the React form validates too, but never trust
    // only the browser)
    private void validate(Manager m) {
        if (m == null) {
            throw new InvalidEmployeeException("Employee data is required");
        }
        if (m.getEname() == null || m.getEname().isBlank()) {
            throw new InvalidEmployeeException("Employee name (ename) is required");
        }
        if (m.getGmail() == null || m.getGmail().isBlank()) {
            throw new InvalidEmployeeException("Email (gmail) is required");
        }
        if (!m.getGmail().trim().matches("^[^\\s@]+@[^\\s@]+\\.[^\\s@]{2,}$")) {
            throw new InvalidEmployeeException("Email (gmail) is not a valid email address");
        }
        if (m.getAge() != null && (m.getAge() < 0 || m.getAge() > 150)) {
            throw new InvalidEmployeeException("Age must be between 0 and 150");
        }
        if (m.getSalary() != null && m.getSalary() < 0) {
            throw new InvalidEmployeeException("Salary cannot be negative");
        }
        if (m.getPhoneno() != null && m.getPhoneno() <= 0) {
            throw new InvalidEmployeeException("Phone number must be a positive number");
        }
    }
}
