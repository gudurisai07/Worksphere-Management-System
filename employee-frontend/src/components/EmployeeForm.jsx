import { useState } from 'react'
import { EMPTY_FORM, LIMITS, fromEmployee, validateEmployee } from '../utils/validation'

/**
 * Create mode: `employee` is null  -> no ID field at all (the database generates eid).
 * Edit mode:   `employee` is given -> ID is shown read-only; it is never editable or sent in the body.
 * The parent gives this component a `key`, so it is re-created (and reset) when the mode changes.
 */
export default function EmployeeForm({ employee, saving, formError, onSubmit, onCancel }) {
  const isEdit = Boolean(employee)
  const [values, setValues] = useState(isEdit ? fromEmployee(employee) : EMPTY_FORM)
  const [touched, setTouched] = useState({})
  const [submitted, setSubmitted] = useState(false)

  const errors = validateEmployee(values)
  const showError = (field) => (touched[field] || submitted) && errors[field]

  function handleChange(e) {
    const { name, value } = e.target
    setValues((prev) => ({ ...prev, [name]: value }))
  }

  function handleBlur(e) {
    const { name } = e.target
    setTouched((prev) => ({ ...prev, [name]: true }))
  }

  function handleSubmit(e) {
    e.preventDefault()
    setSubmitted(true)
    if (Object.keys(errors).length > 0) return
    onSubmit(values)
  }

  function field(name, label, inputProps) {
    const err = showError(name)
    return (
      <div className={`form-group ${err ? 'has-error' : ''}`}>
        <label htmlFor={`f-${name}`}>{label} <span className="required">*</span></label>
        <input
          id={`f-${name}`}
          name={name}
          value={values[name]}
          onChange={handleChange}
          onBlur={handleBlur}
          aria-invalid={Boolean(err)}
          aria-describedby={err ? `f-${name}-err` : undefined}
          disabled={saving}
          {...inputProps}
        />
        {err && <p className="field-error" id={`f-${name}-err`}>{err}</p>}
      </div>
    )
  }

  return (
    <form className="card form-card" id="employee-form" onSubmit={handleSubmit} noValidate>
      <h2>{isEdit ? `Edit Employee #${employee.eid}` : 'Add New Employee'}</h2>

      {isEdit && (
        <div className="form-group">
          <label htmlFor="f-eid">Employee ID</label>
          <input id="f-eid" value={employee.eid} readOnly disabled />
          <p className="hint">The ID is generated by the database and cannot be changed.</p>
        </div>
      )}

      {formError && <div className="alert alert-error" role="alert"><span className="alert-text">{formError}</span></div>}

      {field('ename', 'Name', { type: 'text', placeholder: 'e.g. Sai Kumar', maxLength: LIMITS.nameMax, autoComplete: 'off' })}
      {field('age', 'Age', { type: 'text', inputMode: 'numeric', placeholder: `${LIMITS.ageMin} - ${LIMITS.ageMax}`, maxLength: 3, autoComplete: 'off' })}
      {field('salary', 'Salary', { type: 'text', inputMode: 'decimal', placeholder: 'e.g. 55000', maxLength: 13, autoComplete: 'off' })}
      {field('gmail', 'Email', { type: 'email', placeholder: 'name@example.com', maxLength: LIMITS.emailMax, autoComplete: 'off' })}
      {field('phoneno', 'Phone number', { type: 'text', inputMode: 'numeric', placeholder: '10 digits', maxLength: 10, autoComplete: 'off' })}

      <div className="form-actions">
        <button type="submit" className="btn btn-primary" disabled={saving}>
          {saving ? 'Saving...' : isEdit ? 'Update Employee' : 'Add Employee'}
        </button>
        {isEdit && (
          <button type="button" className="btn btn-secondary" onClick={onCancel} disabled={saving}>
            Cancel
          </button>
        )}
      </div>
    </form>
  )
}
